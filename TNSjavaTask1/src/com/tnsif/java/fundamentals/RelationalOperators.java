package com.tnsif.java.fundamentals;

public class RelationalOperators {

	public static void main(String[] args) {
		int a = 20, b = 5;
        System.out.println("a == b: " + (a == b));
        System.out.println("a != b: " + (a != b));
        System.out.println("a > b: "  + (a > b));
        System.out.println("a < b: "  + (a < b));
        System.out.println("a >= b: " + (a >= b));
        System.out.println("a <= b: " + (a <= b));

	}

}
